def main():
    rows = [(m, "legitimate") for m in LEGIT] + [(m, "promotional") for m in PROMO] \
         + [(m, "suspicious") for m in SUSP] + [(m, "fraud") for m in FRAUD]
    out = Path(__file__).resolve().parents[1] / "data" / "synthetic" / "demo_sms_dataset.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["message", "label"])
        w.writerows(rows)
    print(f"wrote {len(rows)} rows to {out}")

if __name__ == "__main__":
    main()
